"""Generate ambiX adaptor matrices for reduced channel sets.

An adaptor matrix A (L x C, L = (N+1)^2) expands the C channels stored in an
extended ambiX file to the full ACN/SN3D set: full = A . stored. To reduce a
full set for storing, multiply with pinv(A). All families here have
orthonormal columns (A^T A = I), so pinv(A) = A^T, and reduce -> expand is an
orthogonal projector: applying it again changes nothing.

Families
    horizontal  C = 2N+1. Keeps the sectoral harmonics |m| = n, which are all
                a horizontal-only encoder produces (apart from scaled copies).
    mixed       #H#V mixed order: everything up to the vertical order V, plus
                the sectoral harmonics up to the horizontal order H.
                C = (V+1)^2 + 2(H-V). 'horizontal' is the case V = 0.
    hemisphere  C = (N+1)(N+2)/2. Spherical Slepian basis of the cap from the
                zenith down to an elevation a little below the horizon:
                truncated eigendecomposition of the Gram matrix
                G = int_cap y y^T of the N3D harmonics, per azimuthal degree m
                (a zenith-centred cap leaves G block-diagonal in m). Block m
                keeps as many eigenvectors, largest eigenvalue first, as it
                has z-symmetric harmonics (n + |m| even).

References
    Nachbar, Zotter, Deleflie, Sontacchi: "ambiX - A Suggested Ambisonics
    Format", Ambisonics Symposium 2011, sec. 4.3 - 4.5.
    Zotter, Pomberger, Frank: "Ambisonic Decoding with and without
    Mode-Matching: A Case Study Using the Hemisphere", Ambisonics Symposium 2010.
    Zotter, Pomberger: "Spherical Slepian functions for approximation of
    spherical measurement data", DAGA 2012.

The library has 'horizontal' and 'mixed' built in (they are 0/1 matrices) and
ships the 'hemisphere' matrices for orders 1 to 7 as a table generated by this
script (src/hemisphere_tables.hpp).

Usage
    generate_adaptor_matrices.py horizontal 3            # print a matrix, one row per line
    generate_adaptor_matrices.py mixed 3 1               # 3H1V
    generate_adaptor_matrices.py hemisphere 4 --el-min -10
    generate_adaptor_matrices.py hemisphere 4 --format csv -o hemi4.csv
    generate_adaptor_matrices.py --write-tables          # regenerate src/hemisphere_tables.hpp
    generate_adaptor_matrices.py --check                 # verify the families and the shipped table

Needs numpy.
"""

import argparse
import os
import re
import sys
from math import factorial

import numpy as np

MAX_TABLE_ORDER = 7
HERE = os.path.dirname(os.path.abspath(__file__))
TABLE_PATH = os.path.join(HERE, "..", "src", "hemisphere_tables.hpp")

# Lower cap boundary (elevation, degrees) per order. These reproduce, to within
# the quadrature differences of the original, the hemisphere matrices that the
# reaper_ambix plugin has written into files since 2016.
EL_MIN_DEG = {1: -12.824, 2: -24.81, 3: -23.49, 4: -21.35, 5: -18.27, 6: -16.21, 7: -14.18}
DEFAULT_EL_MIN_DEG = -15.0  # for orders without a table entry


def acn(n, m):
    return n * n + n + m


def real_sh_n3d(order, azimuth, colatitude):
    """Real spherical harmonics, N3D, no Condon-Shortley phase (as in ambiX).
    Rows: ACN index, columns: directions."""
    x = np.cos(colatitude)
    s = np.sin(colatitude)
    Y = np.zeros(((order + 1) ** 2, np.size(x)))
    P = {(0, 0): np.ones_like(x)}  # associated Legendre P_n^m(x) without (-1)^m
    for m in range(1, order + 1):
        P[(m, m)] = (2 * m - 1) * s * P[(m - 1, m - 1)]
    for m in range(0, order):
        P[(m + 1, m)] = (2 * m + 1) * x * P[(m, m)]
    for m in range(0, order + 1):
        for n in range(m + 2, order + 1):
            P[(n, m)] = ((2 * n - 1) * x * P[(n - 1, m)] - (n + m - 1) * P[(n - 2, m)]) / (n - m)
    for n in range(order + 1):
        for m in range(-n, n + 1):
            am = abs(m)
            norm = np.sqrt((2 * n + 1) * (2 - (m == 0)) * factorial(n - am) / factorial(n + am))
            trig = np.cos(am * azimuth) if m >= 0 else np.sin(am * azimuth)
            Y[acn(n, m)] = norm * P[(n, am)] * trig
    return Y


def cap_gram(order, el_min_deg, n_quad=256):
    """G = integral over {elevation >= el_min} of y y^T (N3D)."""
    t, w = np.polynomial.legendre.leggauss(n_quad)
    cmin = np.sin(np.radians(el_min_deg))
    c = cmin + (1 - cmin) * (t + 1) / 2
    w = w * (1 - cmin) / 2
    n_az = 2 * order + 2  # exact for trigonometric products up to degree 2*order
    az = 2 * np.pi * np.arange(n_az) / n_az
    C, AZ = np.meshgrid(c, az)
    W = np.tile(w, (n_az, 1)) * (2 * np.pi / n_az)
    Y = real_sh_n3d(order, AZ.ravel(), np.arccos(C.ravel()))
    return (Y * W.ravel()) @ Y.T


# Column k of each matrix belongs to the k-th kept harmonic in ACN order.

def mixed(h_order, v_order):
    if v_order > h_order:
        raise ValueError("the vertical order can not exceed the horizontal order")
    kept = [acn(n, m) for n in range(h_order + 1) for m in range(-n, n + 1) if n <= v_order or abs(m) == n]
    A = np.zeros(((h_order + 1) ** 2, len(kept)))
    for k, row in enumerate(kept):
        A[row, k] = 1.0
    return A


def horizontal(order):
    return mixed(order, 0)


def hemisphere(order, el_min_deg=None):
    if el_min_deg is None:
        el_min_deg = EL_MIN_DEG.get(order, DEFAULT_EL_MIN_DEG)
    G = cap_gram(order, el_min_deg)
    kept = [(n, m) for n in range(order + 1) for m in range(-n, n + 1) if (n + m) % 2 == 0]
    A = np.zeros(((order + 1) ** 2, len(kept)))
    for m in range(-order, order + 1):
        rows = [acn(n, m) for n in range(abs(m), order + 1)]
        slots = [k for k, (_, mm) in enumerate(kept) if mm == m]
        ev, V = np.linalg.eigh(G[np.ix_(rows, rows)])
        V = V[:, np.argsort(ev)[::-1][: len(slots)]]
        for j, k in enumerate(slots):
            v = V[:, j]
            A[rows, k] = v * np.sign(v[np.argmax(np.abs(v))])  # largest entry positive
    return A


# --------------------------------------------------------------- output ---

def format_matrix(A, fmt):
    sep = "," if fmt == "csv" else " "
    return "\n".join(sep.join("%.9g" % (float(np.float32(v)) + 0.0) for v in row) for row in A) + "\n"


def table_source():
    out = [
        "// SPDX-License-Identifier: MIT",
        "// Generated by scripts/generate_adaptor_matrices.py --write-tables - do not edit.",
        "//",
        "// Hemisphere adaptor matrices for orders 1 to %d, row-major, (N+1)^2 rows and" % MAX_TABLE_ORDER,
        "// (N+1)(N+2)/2 columns each.",
        "",
        "namespace ambixfile {",
        "namespace detail {",
        "",
    ]
    for order in range(1, MAX_TABLE_ORDER + 1):
        A = hemisphere(order)
        out.append("// order %d: %d x %d" % (order, A.shape[0], A.shape[1]))
        out.append("static const float kHemisphere%d[] = {" % order)
        for row in A:
            out.append("    " + ", ".join("%.9gf" % (float(np.float32(v)) + 0.0) if "." in "%.9g" % v or "e" in "%.9g" % v
                                           else "%.9g.f" % (float(np.float32(v)) + 0.0) for v in row) + ",")
        out.append("};")
        out.append("")
    out.append("static const float* const kHemisphere[] = {")
    out.append("    " + ", ".join("kHemisphere%d" % o for o in range(1, MAX_TABLE_ORDER + 1)) + ",")
    out.append("};")
    out.append("static const unsigned kHemisphereMaxOrder = %d;" % MAX_TABLE_ORDER)
    out.append("")
    out.append("} // namespace detail")
    out.append("} // namespace ambixfile")
    out.append("")
    return "\n".join(out)


def read_table(path):
    src = open(path, encoding="utf-8").read()
    mats = {}
    for m in re.finditer(r"// order (\d+): (\d+) x (\d+)\s*static const float kHemisphere\d+\[\] = \{(.*?)\};", src, re.S):
        order, rows, cols = int(m[1]), int(m[2]), int(m[3])
        vals = [float(v.strip().rstrip("f")) for v in m[4].replace("\n", " ").split(",") if v.strip()]
        mats[order] = np.array(vals).reshape(rows, cols)
    return mats


def check():
    ok = True

    G = cap_gram(MAX_TABLE_ORDER, -90.0)
    err = np.abs(G / (4 * np.pi) - np.eye(len(G))).max()
    print("N3D harmonics orthonormal on the sphere: %.1e" % err)
    ok &= err < 1e-10

    for order in range(1, MAX_TABLE_ORDER + 1):
        for name, A, cols in (("horizontal", horizontal(order), 2 * order + 1),
                              ("hemisphere", hemisphere(order), (order + 1) * (order + 2) // 2)):
            ortho = np.abs(A.T @ A - np.eye(A.shape[1])).max()
            good = A.shape == ((order + 1) ** 2, cols) and ortho < 1e-9
            print("%-10s N=%d  %2dx%-2d  |AtA-I|=%.1e  %s" % (name, order, *A.shape, ortho, "ok" if good else "FAILED"))
            ok &= good
    for h in range(1, MAX_TABLE_ORDER + 1):
        for v in range(h + 1):
            A = mixed(h, v)
            ok &= A.shape[1] == (v + 1) ** 2 + 2 * (h - v) and np.abs(A.T @ A - np.eye(A.shape[1])).max() == 0
    ok &= mixed(3, 3).shape == (16, 16) and np.array_equal(mixed(3, 3), np.eye(16))
    print("mixed order shapes: %s" % ("ok" if ok else "FAILED"))

    # The shipped table: compared numerically, since the last printed digit may
    # differ between numpy/LAPACK builds.
    shipped = read_table(TABLE_PATH)
    for order in range(1, MAX_TABLE_ORDER + 1):
        A = hemisphere(order)
        S = shipped.get(order)
        diff = np.abs(A - S).max() if S is not None and S.shape == A.shape else float("inf")
        good = diff < 1e-6
        print("shipped table N=%d: max difference %.1e  %s" % (order, diff, "ok" if good else "FAILED"))
        ok &= good
    print("OK" if ok else "FAILED")
    return 0 if ok else 1


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("family", nargs="?", choices=["horizontal", "mixed", "hemisphere"])
    ap.add_argument("order", nargs="?", type=int, help="Ambisonics order (the horizontal order for 'mixed')")
    ap.add_argument("vertical_order", nargs="?", type=int, help="vertical order, for 'mixed'")
    ap.add_argument("--el-min", type=float, help="hemisphere: lower cap boundary, elevation in degrees")
    ap.add_argument("--format", choices=["text", "csv"], default="text")
    ap.add_argument("-o", "--output", help="write here instead of stdout")
    ap.add_argument("--write-tables", action="store_true", help="regenerate src/hemisphere_tables.hpp")
    ap.add_argument("--check", action="store_true", help="verify the families and the shipped table")
    args = ap.parse_args()

    if args.check:
        return check()
    if args.write_tables:
        with open(TABLE_PATH, "w", encoding="utf-8") as f:
            f.write(table_source())
        return 0
    if not args.family or args.order is None or args.order < 0:
        ap.error("give a family and an order, --write-tables or --check")
    if args.family == "mixed":
        if args.vertical_order is None:
            ap.error("'mixed' needs the horizontal and the vertical order")
        A = mixed(args.order, args.vertical_order)
    elif args.family == "horizontal":
        A = horizontal(args.order)
    else:
        A = hemisphere(args.order, args.el_min)
    text = format_matrix(A, args.format)
    if args.output:
        with open(args.output, "w", encoding="utf-8") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
