"""Generate the single-header version of ambixfile.

Usage: amalgamate.py [output path]   (default: single_include/ambixfile.hpp)

The result holds the public header, followed by the implementation inside
#ifdef AMBIXFILE_IMPLEMENTATION. Define that macro in exactly one source file
before including the header.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PUBLIC = "include/ambixfile/ambixfile.hpp"
SOURCES = ["src/internal.hpp", "src/stream.cpp", "src/matrix.cpp", "src/reader.cpp", "src/writer.cpp"]
LOCAL_INCLUDE = re.compile(r'^\s*#\s*include\s+"')


def body(path):
    lines = (ROOT / path).read_text(encoding="utf-8").splitlines()
    return "\n".join(line for line in lines if not LOCAL_INCLUDE.match(line))


def main():
    out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "single_include" / "ambixfile.hpp"
    parts = [
        "// Generated by scripts/amalgamate.py - do not edit.",
        "// Define AMBIXFILE_IMPLEMENTATION in exactly one source file before",
        "// including this header to compile the implementation.",
        "",
        (ROOT / PUBLIC).read_text(encoding="utf-8").rstrip(),
        "",
        "#ifdef AMBIXFILE_IMPLEMENTATION",
        "#ifndef AMBIXFILE_IMPLEMENTATION_INCLUDED",
        "#define AMBIXFILE_IMPLEMENTATION_INCLUDED",
    ]
    for source in SOURCES:
        parts += ["", "// ---- " + source + " ----", body(source)]
    parts += ["", "#endif // AMBIXFILE_IMPLEMENTATION_INCLUDED", "#endif // AMBIXFILE_IMPLEMENTATION", ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(parts), encoding="utf-8")


if __name__ == "__main__":
    main()
